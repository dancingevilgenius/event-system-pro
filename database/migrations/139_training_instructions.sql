-- Run: psql -U postgres -d event_system_pro -f database/migrations/139_training_instructions.sql

\connect event_system_pro

CREATE TABLE IF NOT EXISTS public.training_instructions (
  training_instruction_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instruction_code varchar(64) NOT NULL,
  page_path varchar(128) NOT NULL,
  steps_json jsonb NOT NULL,
  created_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by varchar(128) NOT NULL,
  modified_date timestamptz NULL DEFAULT NULL,
  modified_by varchar(128) NULL DEFAULT NULL,
  CONSTRAINT training_instructions_code_uq UNIQUE (instruction_code)
);

CREATE INDEX IF NOT EXISTS training_instructions_page_path_idx
  ON public.training_instructions (page_path);

COMMENT ON TABLE public.training_instructions IS
  'Coaching lessons. steps_json holds the page, fromPage, and ordered click/select steps.';

ALTER TABLE public.training_instructions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS training_instructions_select_staff ON public.training_instructions;
CREATE POLICY training_instructions_select_staff ON public.training_instructions
  FOR SELECT
  TO authenticated
  USING (api.has_app_role('STAFF') OR api.has_app_role('ADMIN'));

REVOKE ALL ON public.training_instructions FROM PUBLIC;
REVOKE ALL ON public.training_instructions FROM anon;
REVOKE INSERT, UPDATE, DELETE ON public.training_instructions FROM authenticated;
GRANT SELECT ON public.training_instructions TO authenticated;

DROP VIEW IF EXISTS api.training_instructions;
CREATE VIEW api.training_instructions
WITH (security_invoker = true) AS
SELECT
  training_instruction_id,
  instruction_code,
  page_path,
  steps_json
FROM public.training_instructions;

GRANT SELECT ON api.training_instructions TO authenticated;

